function Rewrite([string]$path,[scriptblock]$edit){
    $text=[IO.File]::ReadAllText((Resolve-Path -LiteralPath $path),[Text.Encoding]::UTF8)
    $changed=& $edit $text
    [IO.File]::WriteAllText((Resolve-Path -LiteralPath $path),$changed,[Text.UTF8Encoding]::new($false))
}
